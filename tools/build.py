def write_sitemap():
    seen, out = set(), ['<?xml version="1.0" encoding="UTF-8"?>',
                        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">']
    for key in SITEMAP:
        if key in seen:
            continue
        seen.add(key)
        for lang in ("en", "es"):
            out.append("  <url>\n    <loc>%s</loc>\n    <lastmod>%s</lastmod>" % (abs_url(url(key, lang)), BUILD_DATE))
            for l2 in ("en", "es"):
                out.append('    <xhtml:link rel="alternate" hreflang="%s" href="%s"/>' % (l2, abs_url(url(key, l2))))
            out.append('    <xhtml:link rel="alternate" hreflang="x-default" href="%s"/>' % abs_url(url(key, "en")))
            out.append("  </url>")
    out.append("</urlset>\n")
    with open(os.path.join(ROOT, "sitemap.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))


